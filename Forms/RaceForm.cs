      num = race.EndFuel;
      string str4 = num.ToString();
      textBoxEndFuel.Text = str4;
      TextBox textBoxEndTyres = this.textBoxEndTyres;
      num = race.TyresAfterFinish;
      string str5 = num.ToString();
      textBoxEndTyres.Text = str5;
      if (race.DriverEnergy != null)
      {
        TextBox txtQ1B = this.txtQ1B;
        num = race.DriverEnergy.BeforeQ1;
        string str6 = num.ToString();
        txtQ1B.Text = str6;
        TextBox txtQ1A = this.txtQ1A;
        num = race.DriverEnergy.AfterQ1;
