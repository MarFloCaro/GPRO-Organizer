        num = race.DriverEnergy.BeforeQ2;
        string str8 = num.ToString();
        txtQ2B.Text = str8;
        TextBox txtQ2A = this.txtQ2A;
        num = race.DriverEnergy.AfterQ2;
        string str9 = num.ToString();
        txtQ2A.Text = str9;
        TextBox txtRb = this.txtRB;
        num = race.DriverEnergy.BeforeRace;
        string str10 = num.ToString();
        txtRb.Text = str10;
        TextBox txtRa = this.txtRA;
        num = race.DriverEnergy.AfterRace;
        string str11 = num.ToString();
        txtRa.Text = str11;
      }
      else
        this.grpEnergy.Visible = false;
      if (race.OvertakingAttemps != null)
      {
        TextBox txtIb = this.txtIB;
        num = race.OvertakingAttemps.InitiatedBlocked;
        string str12 = num.ToString();
        txtIb.Text = str12;
